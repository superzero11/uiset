// Writes registry/uiset/ui/address/formats.ts from Google's address data (CC BY 4.0), the
// data Chrome's autofill uses: https://chromium-i18n.appspot.com/ssl-address/data.
// Usage: node scripts/address-data.mjs [dir]. With a dir, it reads <dir>/<CODE>.json and
// fetches only the missing ones; without, it fetches all 252 countries, one at a time.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const service = "https://chromium-i18n.appspot.com/ssl-address/data"
const dir = process.argv[2]
if (dir) mkdirSync(dir, { recursive: true })

async function load(code) {
  const file = dir && join(dir, `${code}.json`)
  if (file && existsSync(file)) return JSON.parse(readFileSync(file, "utf8"))
  const response = await fetch(code === "index" ? service : `${service}/${code}`)
  if (!response.ok) throw new Error(`${code}: ${response.status}`)
  const text = await response.text()
  if (file) writeFileSync(file, text)
  return JSON.parse(text)
}

// The countries whose regions are a list to choose from; elsewhere a region is typed.
const listed = ["US", "CA", "AU", "IN", "BR", "MX", "IT", "ES"]

const fallback = await load("ZZ")
const codes = (await load("index")).countries.split("~")
const formats = {}
const regions = {}
for (const code of codes) {
  const data = await load(code)
  // How the country writes an address, line by line (%n): N the name, O a company, A the
  // street, D a district, C the city, S the region, Z the postal code, X a sorting code, and
  // its own text between them ("CH-%Z"). A form's rows come from it too.
  const fmt = data.fmt ?? fallback.fmt
  const format = {}
  if (fmt !== fallback.fmt) format.fmt = fmt
  const require = (data.require ?? fallback.require).replace(/[^ADCSZ]/g, "")
  if (require !== "AC") format.require = require
  if (data.zip) {
    format.zip = data.zip
    format.example = data.zipex?.split(",")[0]
    if (/Z/.test(data.upper ?? "")) format.upper = true
  }
  if (data.zip_name_type && data.zip_name_type !== "postal") format.postal = data.zip_name_type
  if (data.state_name_type && data.state_name_type !== "province") format.region = data.state_name_type
  if (data.locality_name_type && data.locality_name_type !== "city") format.city = data.locality_name_type
  if (data.sublocality_name_type && data.sublocality_name_type !== "suburb") format.district = data.sublocality_name_type
  formats[code] = format
  if (listed.includes(code)) {
    const keys = data.sub_keys.split("~")
    const names = (data.sub_names ?? data.sub_keys).split("~")
    const zips = data.sub_zips?.split("~") ?? []
    regions[code] = keys.map((key, index) => (zips[index] ? [key, names[index], zips[index]] : [key, names[index]]))
  }
}

const out = `// Generated by scripts/address-data.mjs on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand.
// From Google's address data (https://chromium-i18n.appspot.com/ssl-address/data), licensed
// CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/); compacted to what a form needs.

/** How a country writes an address. Missing keys take the defaults in \`address.ts\`. */
type AddressFormat = {
  /** Its lines, split by %n: %N name, %O company, %A street, %D district, %C city, %S region, %Z postal code, %X sorting code, and its own text. */
  fmt?: string
  /** The parts it requires, by the same letters. */
  require?: string
  /** The postal code's shape, a regular expression for the whole code. */
  zip?: string
  example?: string
  /** Postal codes are written in capitals. */
  upper?: boolean
  postal?: string
  region?: string
  city?: string
  district?: string
}

/** A region's key (what the address prints), its name, and the start its postal codes share. */
type Region = readonly [key: string, name: string, zip?: string]

const addressFormats: Record<string, AddressFormat> = ${JSON.stringify(formats, null, 0)
  .replace(/^\{/, "{\n  ")
  .replace(/\},"/g, '},\n  "')
  .replace(/\}$/, ",\n}")}

const addressRegions: Record<string, readonly Region[]> = {
${Object.entries(regions)
  .map(([code, list]) => `  ${code}: ${JSON.stringify(list)},`)
  .join("\n")}
}

export { addressFormats, addressRegions }
export type { AddressFormat, Region }
`
writeFileSync(new URL("../registry/uiset/ui/address/formats.ts", import.meta.url), out)
console.log(`${codes.length} countries, regions for ${Object.keys(regions).join(", ")}`)
