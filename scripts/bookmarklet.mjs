// Bundles the agent-readiness bookmarklet: src/site/agent-check-bookmarklet.ts and the check it
// runs, into one script a bookmark can hold. Writes src/site/generated/agent-check-bookmarklet.ts
// with the sources' hash, which tests/unit/agent-check-page.test.ts compares to catch a stale
// bundle. Run it after changing registry/uiset/ui/agent-check/{check,page,overlay}.ts.
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { build } from "vite"

const root = fileURLToPath(new URL("..", import.meta.url))
const sources = [
  "src/site/agent-check-bookmarklet.ts",
  "registry/uiset/ui/agent-check/check.ts",
  "registry/uiset/ui/agent-check/page.ts",
  "registry/uiset/ui/agent-check/overlay.ts",
]
const hash = createHash("sha256")
for (const file of sources) hash.update(readFileSync(`${root}${file}`))
const digest = hash.digest("hex").slice(0, 16)

const [output] = [].concat(
  await build({
    configFile: false,
    logLevel: "warn",
    resolve: { alias: { "@": root.replace(/\/$/, "") } },
    build: {
      write: false,
      minify: true,
      lib: { entry: `${root}src/site/agent-check-bookmarklet.ts`, formats: ["iife"], name: "uisetAgentCheck", fileName: () => "agent-check.js" },
    },
  }),
)
const code = output.output[0].code.trim()

writeFileSync(
  `${root}src/site/generated/agent-check-bookmarklet.ts`,
  `// Generated by scripts/bookmarklet.mjs from ${sources.join(", ")}. Don't edit it.\n` +
    `// sources: ${digest}\n` +
    `export default ${JSON.stringify(code)}\n`,
)
console.log(`bookmarklet: ${(code.length / 1024).toFixed(1)} KB, sources ${digest}`)
