// Bundles the site's functions for Vercel: api/_agent-check/handler.ts and what it imports,
// into api/agent-check.js. Vercel compiles a TypeScript function with the project's own
// TypeScript, which it can't drive in version 7, so it gets JavaScript. The browser packages
// stay imports, for Vercel to install. The header holds the sources' hash, which
// tests/unit/agent-check-guard.test.ts compares to catch a stale bundle.
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { build } from "vite"

const root = fileURLToPath(new URL("..", import.meta.url))
const [result] = [].concat(
  await build({
    configFile: false,
    logLevel: "warn",
    build: {
      ssr: `${root}api/_agent-check/handler.ts`,
      write: false,
      minify: false,
      target: "node22",
      rollupOptions: { external: [/^node:/, "playwright-core", "@sparticuz/chromium-min"], output: { format: "es" } },
    },
  }),
)
const [chunk] = result.output
const code = chunk.code
// Every file in the bundle, in a fixed order, so the hash changes whenever any of them does.
const sources = chunk.moduleIds
  .filter((id) => id.startsWith(root) && !id.includes("/node_modules/"))
  .map((id) => id.slice(root.length))
  .sort()
const hash = createHash("sha256")
for (const file of sources) hash.update(readFileSync(`${root}${file}`))
const digest = hash.digest("hex").slice(0, 16)

writeFileSync(`${root}api/agent-check.js`, `// Generated by scripts/api.mjs from ${sources.join(", ")}. Don't edit it.\n// sources: ${digest}\n${code}`)
console.log(`api/agent-check.js: ${(code.length / 1024).toFixed(1)} KB, sources ${digest}`)
