import { afterEach, expect, test } from "vitest"
import { CheckError, isPublicAddress, publicUrl } from "@/api/_agent-check/guard"

// The link checker's address guard: it loads public web pages only, never a private network.

afterEach(() => {
  delete process.env.AGENT_CHECK_ALLOW_PRIVATE
})

test("public addresses pass; private, loopback, link-local, shared, reserved and multicast don't", () => {
  for (const ip of ["93.184.215.14", "8.8.8.8", "1.1.1.1", "2606:4700::6810:84e5", "2a00:1450:4001:82a::200e"]) expect(isPublicAddress(ip), ip).toBe(true)
  for (const ip of [
    "10.0.0.1", "172.16.5.4", "172.31.255.255", "192.168.1.1", "127.0.0.1", "0.0.0.0", "169.254.169.254",
    "100.64.0.1", "198.18.0.1", "192.0.2.10", "224.0.0.1", "255.255.255.255",
    "::1", "::", "fc00::1", "fd12:3456::1", "fe80::1", "ff02::1", "2001:db8::1",
    "::ffff:10.0.0.1", "::ffff:127.0.0.1", "64:ff9b::192.168.0.1",
    // The same addresses written other ways: as URLs print them, in full, and through 6to4.
    "::ffff:7f00:1", "::ffff:a9fe:a9fe", "0:0:0:0:0:0:0:1", "0000:0000:0000:0000:0000:ffff:0a00:0001", "2002:7f00:1::", "2002:c0a8:101::1",
    // Teredo, benchmarking, the new documentation block, local NAT64, site-local, discard, zone ids.
    "2001:0:4136:e378:8000:63bf:3fff:fdd2", "2001:2::1", "3fff::1", "64:ff9b:1::1", "fec0::1", "100::1", "fe80::1%eth0",
  ]) expect(isPublicAddress(ip), ip).toBe(false)
  // Edges of the ranges.
  expect(isPublicAddress("172.15.255.255")).toBe(true)
  expect(isPublicAddress("172.32.0.0")).toBe(true)
  expect(isPublicAddress("100.128.0.0")).toBe(true)
  expect(isPublicAddress("::ffff:8.8.8.8")).toBe(true)
  expect(isPublicAddress("::ffff:808:808")).toBe(true)
  expect(isPublicAddress("2002:808:808::1")).toBe(true)
  expect(isPublicAddress("2001:200::1")).toBe(true)
  expect(isPublicAddress("not an ip")).toBe(false)
})

test("an address gets https:// when it has none, and only web addresses on the usual ports pass", async () => {
  expect((await publicUrl("1.1.1.1")).href).toBe("https://1.1.1.1/")
  // A public IPv6 address, in its brackets.
  expect((await publicUrl("https://[2606:4700:4700::1111]/")).hostname).toBe("[2606:4700:4700::1111]")
  // A host and a port aren't a scheme.
  expect((await publicUrl("8.8.8.8:443/docs")).href).toBe("https://8.8.8.8/docs")
  expect((await publicUrl("http://8.8.8.8/path?q=1")).href).toBe("http://8.8.8.8/path?q=1")
  const refused = async (input: string | null) => {
    const error = await publicUrl(input).catch((e: unknown) => e)
    expect(error, input ?? "null").toBeInstanceOf(CheckError)
    return (error as Error).message
  }
  expect(await refused(null)).toBe("Enter a web address, like example.com.")
  expect(await refused("   ")).toBe("Enter a web address, like example.com.")
  expect(await refused("ftp://8.8.8.8/")).toBe("Only http and https addresses can be checked.")
  expect(await refused("file:///etc/passwd")).toBe("Only http and https addresses can be checked.")
  expect(await refused("javascript:alert(1)")).toBe("Only http and https addresses can be checked.")
  expect(await refused("https://user:secret@8.8.8.8/")).toBe("Leave the user name and password out of the address.")
  expect(await refused("https://8.8.8.8:8443/")).toBe("Only addresses on the usual web ports (80 and 443) can be checked.")
  expect(await refused("https://exa mple.com")).toContain("isn't a web address")
})

test("private hosts are refused, by name and by number, unless a test on this machine allows them", async () => {
  for (const input of [
    "localhost:3000", "http://localhost/", "http://127.0.0.1/", "http://[::1]/", "http://169.254.169.254/latest/meta-data", "http://192.168.0.10/", "printer.local", "db.internal",
    // A URL prints a mapped address in hex: [::ffff:7f00:1].
    "http://[::ffff:127.0.0.1]/", "http://[0:0:0:0:0:ffff:a9fe:a9fe]/", "http://0x7f.1/", "http://2130706433/",
  ]) {
    await expect(publicUrl(input), input).rejects.toThrow("private network or couldn't be found")
  }
  process.env.AGENT_CHECK_ALLOW_PRIVATE = "1"
  expect((await publicUrl("http://127.0.0.1:5631/")).href).toBe("http://127.0.0.1:5631/")
  // Never where it's deployed.
  process.env.VERCEL = "1"
  await expect(publicUrl("http://127.0.0.1/")).rejects.toThrow("private network")
  delete process.env.VERCEL
})

test("the function's bundle was built from its sources as they are now", async () => {
  const { createHash } = await import("node:crypto")
  const { readFileSync } = await import("node:fs")
  const bundle = readFileSync("api/agent-check.js", "utf8")
  const sources = /^\/\/ Generated by scripts\/api\.mjs from (.+)\. Don't edit it\.$/m.exec(bundle)![1]!.split(", ")
  const hash = createHash("sha256")
  for (const file of sources) hash.update(readFileSync(file))
  expect(/^\/\/ sources: (\w+)$/m.exec(bundle)![1], "api/agent-check.js is stale: run node scripts/api.mjs").toBe(hash.digest("hex").slice(0, 16))
})
